/*
 * OpenIMP T32 HERA H.264 command lists (#293, planned; not a release gate).
 *
 * HERA (the T32 video encoder, soc_vpu "radix0") runs a command list from
 * memory: pairs of words (value, then VLD bit 31 | TERM bit 30 | checksum
 * bits 29:20 | register offset bits 19:0), modules 0x8000 apart.  The
 * checksum is the 10-bit sum of the value's four bytes and the offset's two
 * low bytes.  The last pair (CFGC ACM_CTRL, TERM) ends the list; the one
 * before it (EFE STAT = 1) starts the picture.
 *
 * t32_hera_h264_list() writes the list of one H.264 picture.  The register
 * order and the defaults of the analysis / mode-decision registers are
 * vendor libimp 2.2.0's at FIXQP (tests/t32/vendor-2.2.0-hera-h264.txt.gz,
 * table generated by tools/t32/hera_h264_table.py); sizes, addresses, the
 * QP and the CABAC context states are computed here.  No rate control: the
 * hardware QP generator stays off, one QP per picture.
 *
 * Reconstruction / reference: one ring per plane (buffer share), the
 * picture's rows (rounded up to 64) plus T32_HERA_RING_EXTRA rows; an I picture is
 * reconstructed at the ring's base, each P picture T32_HERA_RING_EXTRA rows
 * before its reference, over the reference's rows already read.
 */
#ifndef OPENIMP_T32_HERA_H
#define OPENIMP_T32_HERA_H

#include <stddef.h>
#include <stdint.h>

#define T32_HERA_RING_EXTRA     128u    /* ring rows beyond the picture */
#define T32_HERA_LIST_MAX_PAIRS 1024u   /* I 736, P 913 */
#define T32_HERA_LIST_BYTES     (T32_HERA_LIST_MAX_PAIRS * 8u)

typedef struct {
    uint32_t width, height;             /* picture size, multiples of 16 */
    int p_frame;                        /* 0 I (IDR), 1 P (one reference) */
    int qp;                             /* 0..51 */
    uint32_t src_y, src_c, src_stride;  /* NV12 source */
    uint32_t ring_y, ring_y_end;        /* reconstruction ring, luma: base, beyond */
    uint32_t ring_c, ring_c_end;        /* chroma */
    uint32_t recon_y, recon_c;          /* this picture's reconstruction in the ring */
    uint32_t ref_y, ref_c;              /* P: the reference in the ring */
    uint32_t bs0, bs1;                  /* stream: one buffer (bs1 0) or two halves */
    uint32_t section_kb;                /* 0: no sections; else BSFULL after this many KiB */
    uint32_t cps, ai, qpt, ipc;         /* analysis outputs (t32_hera_aux_sizes) */
    const uint8_t *rc_slice;            /* NULL, or the T33 controller's slice block (below) */
} T32HeraH264Pic;

/* the ring's stride and rows per plane (luma; chroma has half the rows) */
static inline uint32_t t32_hera_ring_stride(uint32_t width) { return (width + 63u) & ~63u; }
/* the picture's rows rounded up to 64 (the MCE counts the ring in 64-row
 * units: vendor 1088 -> 1216, 720 -> 896) plus the extra rows */
static inline uint32_t t32_hera_ring_rows(uint32_t height) { return ((height + 63u) & ~63u) + T32_HERA_RING_EXTRA; }

/* sizes of the analysis buffers the engine writes (cps, ai, qpt, ipc) */
void t32_hera_aux_sizes(uint32_t width, uint32_t height, uint32_t size[4]);

/* the P picture after a picture at recon: its reconstruction address in the
 * ring (T32_HERA_RING_EXTRA rows before, wrapping at the base) */
uint32_t t32_hera_ring_prev(uint32_t addr, uint32_t base, uint32_t end, uint32_t rows_bytes);

/*
 * Rate control (#295): with @rc_slice (the vendor-layout slice block of the
 * T33 controller, T33_SLICE_BYTES, revision 6) the registers vendor
 * H264E_T32V_SliceInit fills from it come from there, as the vendor does:
 * EFE_FRM_QP (picture QP, MB QP window s+0x826 / s+0x825), EFE 0x2029c (MB
 * QP clamp s+0x76e / s+0x76f, map enables), the row-budget block
 * 0x40100..0x40124 and, after it, one 0x40900 + 4 i word a 64-line row
 * (s+0x568, s+0x530 of them).  Other values stay the FIXQP defaults.
 */
/* the list into @list (T32_HERA_LIST_MAX_PAIRS * 2 words): pairs written, 0 on bad input */
size_t t32_hera_h264_list(const T32HeraH264Pic *p, uint32_t *list);

/* FIXQP analysis defaults shared by H.264 and H.265 (vendor 2.2.0, by QP):
 * EFE complexity QP offsets (@which 0: 0x2003c, 1: 0x20040) and the four
 * ROI slots' control bytes (0x20054..0x20060) */
uint32_t t32_hera_cplx_qp(uint32_t qp, int which);
uint32_t t32_hera_roi_info(int qp);

/* one pair's command word */
uint32_t t32_hera_cmd(uint32_t reg, uint32_t value, int term);

/* the CABAC context state of H.264 ctxIdx 0..459 for slice type and QP
 * (cabac_init_idc 0), as preCtxState 1..126 */
void t32_hera_cabac_states(int p_frame, int qp, uint8_t state[460]);
/* the SDE context table word of CABAC state @state, and the QP generator's
 * delta thresholds (0x20300) by QP: shared with the T33 builder (#391) */
uint32_t t32_hera_sde_ctx(unsigned state);
uint32_t t32_hera_qpg_dlt(uint32_t qp);

#endif
