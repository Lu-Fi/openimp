#!/usr/bin/env python3
"""Make src/t32/openimp_t32_hera_tab.h from a vendor libimp 2.2.0 H.264 trace (#293).

The HERA H.264 command list of vendor libimp 2.2.0 is a fixed register
sequence per picture type (I: 736 pairs, P: 913; P adds the MCE/TFM block):
the same registers in the same order at every QP and size measured.  This
script takes one I and one P list of a FIXQP trace (tools/t32/hera_list.py
input: "V" lines of tools/t32/t32_ioctl_trace.c, T32_TRACE_VPU=12288) and
writes the merged order with the default values as a C table.  Registers
the builder computes (sizes, addresses, QP, CABAC states: COMPUTED below)
are written as 0; the two CABAC context runs become one entry each.

usage: hera_h264_table.py RAW.LOG [I job] [P job] > src/t32/openimp_t32_hera_tab.h
       hera_h264_table.py --t33 RAW.LOG [I job] [P job] > src/t32/openimp_t33_hera_tab.h

--t33 (#391): a vendor libimp 2.0.2.1 trace (QEMU -M ingenic-t33, HERA v1.6;
I 776 pairs, P 811): VMAU at 0x40400 (context states 0x40448), the ring
compression registers, COMPUTED_T33 below (openimp_t33_hera.c).
"""
import difflib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hera_list import jobs  # noqa: E402

# registers openimp_t32_hera.c fills in (hera_field); their table value is 0
COMPUTED = {
    0x20008, 0x2000c, 0x20010, 0x20014, 0x2001c, 0x2003c, 0x20040,
    0x20054, 0x20058, 0x2005c, 0x20060, 0x20300,
    0x28004, 0x28014, 0x28018, 0x2801c, 0x28020, 0x28024, 0x28028, 0x2802c,
    0x30060, 0x30064, 0x30070, 0x30074, 0x30078, 0x30800, 0x30804,
    0x80030, 0x80054, 0x80114,
    0x68008, 0x68018,
    0x9005c, 0x90064, 0x90008, 0x9001c, 0x9000c, 0x90050, 0x90028, 0x90030, 0x90038,
    0x10004, 0x10008, 0x1000c, 0x10030, 0x10034, 0x10038, 0x1003c,
}
# T33 (HERA v1.6): what openimp_t33_hera.c fills in (t33_field)
COMPUTED_T33 = {
    0x20008, 0x2000c, 0x20010, 0x20014, 0x2001c, 0x2003c, 0x20040, 0x20300,
    0x28004, 0x28008, 0x2800c, 0x28014, 0x28018, 0x2801c, 0x28020, 0x28024, 0x28028, 0x2802c,
    0x30060, 0x30064, 0x30070, 0x30074, 0x30078, 0x3007c, 0x30800, 0x30804,
    0x4040c, 0x40410, 0x4042c, 0x50000, 0x7000c,
    0x68008, 0x68018,
    0x9005c, 0x90064, 0x90008, 0x9001c, 0x9000c, 0x90050, 0x90028, 0x9002c, 0x90030, 0x90038,
    0x10004, 0x10008, 0x1000c, 0x10020, 0x10024, 0x10028, 0x1002c,
    0x10030, 0x10034, 0x10038, 0x1003c,
}
VMAU_CTX, SDE_CTX, SDE_CTX_N = 0x8002c, 0x6a000, 460


def merge(i_list, p_list):
    """[(reg, vi, vp, when)], when 1 = I only, 2 = P only, 3 = both"""
    ri, rp = [r for _, r in i_list], [r for _, r in p_list]
    out = []
    sm = difflib.SequenceMatcher(None, ri, rp, autojunk=False)
    for op, i1, i2, j1, j2 in sm.get_opcodes():
        if op == "equal":
            for k in range(i2 - i1):
                out.append((ri[i1 + k], i_list[i1 + k][0], p_list[j1 + k][0], 3))
        elif op == "insert":
            for k in range(j1, j2):
                out.append((rp[k], 0, p_list[k][0], 2))
        elif op == "delete":
            for k in range(i1, i2):
                out.append((ri[k], i_list[k][0], 0, 1))
        else:
            raise SystemExit("I and P lists differ in order at I %d / P %d" % (i1, j1))
    return out


def main():
    global COMPUTED, VMAU_CTX
    args = sys.argv[1:]
    t33 = bool(args) and args[0] == "--t33"
    if t33:
        args = args[1:]
        COMPUTED, VMAU_CTX = COMPUTED_T33, 0x40448
    js = jobs(args[0])
    ij = int(args[1]) if len(args) > 1 else 0
    pj = int(args[2]) if len(args) > 2 else 1
    norm = lambda job: [(v, c & 0xffffc) for v, c in job]  # noqa: E731
    m = merge(norm(js[ij]), norm(js[pj]))
    rows, k = [], 0
    while k < len(m):
        reg, vi, vp, when = m[k]
        if reg == SDE_CTX:
            n = 0
            while k + n < len(m) and m[k + n][0] == SDE_CTX + 4 * n:
                n += 1
            assert n == SDE_CTX_N, n
            rows.append((reg, 0, 0, when, n, "SDE CABAC context table"))
            k += n
            continue
        if reg == VMAU_CTX:
            n = 0
            while k + n < len(m) and m[k + n][0] == VMAU_CTX:
                n += 1
            rows.append((reg, 0, 0, when, n, "VMAU context states"))
            k += n
            continue
        if reg in COMPUTED:
            vi = vp = 0
        rows.append((reg, vi if when & 1 else 0, vp if when & 2 else 0, when, 1, None))
        k += 1
    if t33:
        print("/* Generated by tools/t32/hera_h264_table.py --t33 from a vendor libimp 2.0.2.1")
        print(" * FIXQP trace (QEMU -M ingenic-t33, HERA v1.6, #391): the H.264 command list's")
        print(" * register order and default values per picture type; registers")
        print(" * openimp_t33_hera.c computes are 0 here.  {reg, I value, P value, n, when} */")
        print("static const T32HeraEnt t33_hera_h264_tab[] = {")
    else:
        print("/* Generated by tools/t32/hera_h264_table.py from a vendor libimp 2.2.0 FIXQP")
        print(" * trace (QEMU -M ingenic-t32, #293): the HERA H.264 command list's register")
        print(" * order and default values per picture type; registers openimp_t32_hera.c")
        print(" * computes are 0 here.  {reg, I value, P value, n, when: 1 I, 2 P, 3 both} */")
        print("static const T32HeraEnt t32_hera_h264_tab[] = {")
    for reg, vi, vp, when, n, note in rows:
        line = "    { 0x%05x, 0x%08x, 0x%08x, %3d, %d }," % (reg, vi, vp, n, when)
        if note:
            line += "  /* %s */" % note
        print(line)
    print("};")
    print("/* pairs: I %d, P %d */" % (sum(r[4] for r in rows if r[3] & 1), sum(r[4] for r in rows if r[3] & 2)))


if __name__ == "__main__":
    main()
