#!/bin/bash
# scene_ae_test.sh <soc: t31|t20|t20j> <clip: grey|ramp_up|ramp_down|step|tint|all> [outdir]
# AE/AWB regression on QEMU ingenic-0.7.14 with a real-video sensor input (image-sensor "scene=" y4m clip):
# boots the SoC's open-stack flash image (read-only, snapshot=on), loads the ISP stack with the camera daemon's day/night
# switching neutralised, samples AE/AWB/luma from inside the guest while the clip plays (tools/qemu/ae_sample.sh) and
# checks the result (tools/qemu/ae_analyze.py). One QEMU at a time, pinned to CPUs 2-15 at nice 19.
# Env: Q (QEMU work dir with build/ and 1a-*/ images), CLIPS (y4m dir, generated by gen_scenes.sh if missing),
#      FPS (sensor model frame rate, default 15 = the sensor mode's rate), PORT, MAXFRAMES (frames sampled from the first row, default 1500),
#      FLASH (image override), STACK (open|vendor; vendor = see README, not available from the 1a-* images).
set -u
HERE=$(cd "$(dirname "$0")" && pwd)
SOC=${1:?soc t31|t20}; CLIP=${2:?clip}; OUT=${3:-$HERE/../../audit/qemu-scene}
Q=${Q:-/mnt/NVMe/git/scratch-clones/session-110bf918/qemu}
CLIPS=${CLIPS:-$Q/scene-ae}; FPS=${FPS:-15}; PORT=${PORT:-3990}; MAXF=${MAXFRAMES:-1500}
STACK=${STACK:-open}
case $SOC in
  t31) MACH="-M ingenic-t31 -m 128M"; SENS=sc2336; FLASH=${FLASH:-$Q/1a-t31/t31.bin};;
  t20) MACH="-M ingenic-t20 -m 128M -global ingenic-t31.soc-variant=t20x"; SENS=jxf23; FLASH=${FLASH:-$Q/1a-t20/t20.bin};;
  t20j) MACH="-M ingenic-t20 -m 128M -global ingenic-t31.soc-variant=t20x"; SENS=jxf22; FLASH=${FLASH:-$Q/1a-t20-jxf22/t20.bin};;
  *) echo "soc t31|t20|t20j (t20j: T20X image with the jxf22, the T20-class sensor the model exposes exposure for)"; exit 2;;
esac
# sensor models of QEMU 0.7.14 without an exposure model: the picture does not follow the exposure, the AE loop stays open
case $SENS in jxf22|gc2053|sc4236|os02g10|os08c10|cv2005) LOOP="";; *) LOOP="--open-loop";; esac
if [ "$CLIP" = all ]; then
  for c in grey step ramp_up ramp_down tint; do "$0" "$SOC" "$c" "$OUT" || true; done; exit 0
fi
mkdir -p "$OUT"
[ -f "$CLIPS/$CLIP.y4m" ] || "$HERE/gen_scenes.sh" "$CLIPS" >/dev/null || exit 1
if pgrep -f "qemu-system-mipsel.*port=$PORT" >/dev/null; then echo "QEMU on port $PORT already running"; exit 1; fi
TAG=$SOC-$STACK-$CLIP; RAW=$OUT/$TAG.raw
echo "[$TAG] boot ($(pgrep -c qemu-system) other qemu-system running, not touched)"
taskset -c 2-15 nice -n 19 "$Q/build/qemu-system-mipsel" $MACH -display none \
  -drive file="$FLASH",format=raw,if=none,id=flash0,snapshot=on -serial null \
  -chardev socket,id=con,host=127.0.0.1,port=$PORT,server=on,wait=off,logfile="$OUT/$TAG.console" -serial chardev:con \
  -netdev user,id=n0 -device image-sensor,model=$SENS,bus=i2c0,fps=$FPS,scene="$CLIPS/$CLIP.y4m" \
  > "$OUT/$TAG.qemu" 2>&1 &
QP=$!
trap 'kill $QP 2>/dev/null' EXIT
GC="python3 $HERE/guest_console.py $PORT"
$GC waitsh 400 || exit 1
$GC put "$HERE/ae_sample.sh" /tmp/ae.sh >/dev/null
case $SOC in
  t31|t20) # the image ships the ISP stack suspended (boot guard): load it in the background. The camera daemon samples ae_luma only
       # while its day/night thread runs; switch and IR-probe commands become `true`, so the ISP stays in day mode.
    $GC run 'printf "daynight.enabled = 1\ndaynight.switch_cmd = true\ndaynight.irprobe_cmd = true\ndaynight.interval_ms = 500\nimage.running_mode = 0\n" >> /etc/timps.conf; (/etc/init.d/S10isp-guard load >/tmp/load.log 2>&1 &)' 20 >/dev/null;;
  *)   # the T20X jxf22 image starts the ISP and the daemon at boot, so the clip would already be mid-loop: restart the daemon (sensor
       # stream off/on, the clip starts again at frame 0), count the ISP interrupts from there, day/night off, ISP in day mode
    $GC run 'awk '"'"'$NF=="isp" {print $2}'"'"' /proc/interrupts > /tmp/ae_base; /etc/init.d/S95timps restart >/dev/null 2>&1; T=$(head -n1 /run/timps.token|tr -cd 0-9A-Za-z); n=0; until curl -s -m 2 -H "X-Timps-Token: $T" http://127.0.0.1:8880/control >/dev/null 2>&1 || [ $n -gt 40 ]; do n=$((n+1)); sleep 1; done' 80 >/dev/null
    $GC run 'T=$(head -n1 /run/timps.token|tr -cd 0-9A-Za-z); for j in "{\"daynight\":{\"enabled\":false}}" "{\"image\":{\"running_mode\":0}}"; do curl -s -m 10 -X POST -H "X-Timps-Token: $T" -H "Content-Type: application/json" -d "$j" http://127.0.0.1:8880/control >/dev/null; done' 40 >/dev/null;;
esac
LU=1; [ "$SOC" = t31 ] || LU=0   # only the T31 stack has an AE luma query
$GC stream "/tmp/ae.sh $MAXF 400 0 $LU" 900 AE_DONE | grep -a '^AE' > "$RAW"
echo "[$TAG] $(grep -c '^AE,' "$RAW") rows; dmesg errors: $($GC run 'dmesg | grep -c -E "Oops|Bus error|Kernel panic"' 20 | grep -a -E '^[0-9]+$' | tail -1)"
kill $QP 2>/dev/null; wait $QP 2>/dev/null; trap - EXIT
python3 "$HERE/ae_analyze.py" "$RAW" --soc "$SOC" --clip "$CLIP" --fps "$FPS" --stack "$STACK" --out "$OUT" $LOOP
