#!/usr/bin/env python3
"""Generates src/framesource/nv12_rotate_mxu2_gen.h (MXU2 tile transposes).

A 16x16 byte block (8x8 for 16-bit CbCr pairs) is transposed with four
(three) rounds of the same perfect shuffle: new[2j] = lo(old[j], old[j+N/2]),
new[2j+1] = hi(old[j], old[j+N/2]), one SHUFV each.  The generator keeps the
rows in a pool of N+1 vector registers and renames instead of copying: lo
goes to the free register, hi overwrites old[j+N/2], old[j]'s register
becomes the free one.  It checks the schedule against a model of SHUFV
before writing the header.

SHUFV vd, vs, vt, vr (device-checked): the 32 source bytes are interleaved,
op[2i] = vt[i], op[2i+1] = vs[i]; vd[k] = vr[k] & 0x80 ? 0 : op[vr[k] & 31].

    python3 tools/gen_nv12_rotate_mxu2.py > src/framesource/nv12_rotate_mxu2_gen.h
"""
import sys

IDX_LO8, IDX_HI8, IDX_LO16, IDX_HI16 = 24, 25, 26, 27


def shufv(vs, vt, idx):
    op = []
    for i in range(16):
        op += [vt[i], vs[i]]
    return [None if k & 0x80 else op[k & 31] for k in idx]


def il_idx(esize, hi):
    """vd = interleave of esize-byte elements of vt (even) and vs (odd)."""
    out = []
    per = 16 // esize
    for q in range(per):
        src_vs = q % 2
        el = q // 2 + (per // 2 if hi else 0)
        for b in range(esize):
            out.append(2 * (el * esize + b) + src_vs)
    return out


def schedule(n, esize, rounds):
    """Returns (ops, final register of logical row L)."""
    slot = list(range(n))          # logical row -> register
    free = n
    ops = []
    lo_r = IDX_LO8 if esize == 1 else IDX_LO16
    hi_r = IDX_HI8 if esize == 1 else IDX_HI16
    for _ in range(rounds):
        new = [None] * n
        for j in range(n // 2):
            a, b = slot[j], slot[j + n // 2]
            ops.append((free, b, a, lo_r))      # vd, vs, vt, vr
            ops.append((b, b, a, hi_r))
            new[2 * j], new[2 * j + 1] = free, b
            free = a
        slot = new
    return ops, slot


def check(n, esize, rounds):
    ops, slot = schedule(n, esize, rounds)
    lo = il_idx(esize, False)
    hi = il_idx(esize, True)
    tab = {IDX_LO8: il_idx(1, False), IDX_HI8: il_idx(1, True),
           IDX_LO16: il_idx(2, False), IDX_HI16: il_idx(2, True)}
    assert tab[IDX_LO8] == list(range(16)) and tab[IDX_HI8] == list(range(16, 32))
    del lo, hi
    per = 16 // esize
    reg = {}
    for i in range(n):
        reg[i] = [(i, k // esize, k % esize) for k in range(16)]
    for vd, vs, vt, vr in ops:
        reg[vd] = shufv(reg[vs], reg[vt], tab[vr])
    for j in range(n):
        for i in range(per):
            for b in range(esize):
                assert reg[slot[j]][i * esize + b] == (i, j, b), (j, i, b)
    return ops, slot


def emit_fn(name, n, esize, rounds, out, rev):
    ops, slot = check(n, esize, rounds)
    out.append("/* %dx%d %s transpose: rows s, s+ss, ... -> rows d, d+ds, ...\n"
               " * (%d SHUFV, %d loads, %d stores)%s. */" %
               (n, n, "byte" if esize == 1 else "pair", len(ops), n, n,
                "; loads issued last row first,\n * i.e. in ascending"
                " address order when ss < 0" if rev else ""))
    out.append("static inline void %s(const uint8_t *s, ptrdiff_t ss,\n"
               "    uint8_t *d, ptrdiff_t ds)\n{" % name)
    for i in (range(n - 1, -1, -1) if rev else range(n)):
        out.append("    VLOAD(%d, s + %d * ss);" % (i, i))
    for vd, vs, vt, vr in ops:
        out.append("    VSHUF(%d, %d, %d, %d);" % (vd, vs, vt, vr))
    for j in range(n):
        out.append("    VSTORE(%d, d + %d * ds);" % (slot[j], j))
    out.append("}\n")


def main():
    out = ["/* Generated by tools/gen_nv12_rotate_mxu2.py - do not edit. */",
           "#define NV12_MXU2_IDX_LO8  %d" % IDX_LO8,
           "#define NV12_MXU2_IDX_HI8  %d" % IDX_HI8,
           "#define NV12_MXU2_IDX_LO16 %d" % IDX_LO16,
           "#define NV12_MXU2_IDX_HI16 %d" % IDX_HI16,
           "#define NV12_MXU2_IDX_REV8 28",
           "#define NV12_MXU2_IDX_REV16 29",
           "/* vr0..vr16 data, vr24..vr29 index vectors */",
           "#define NV12_MXU2_LAST_VR 29",
           "static const uint8_t nv12_mxu2_idx[6][16] __attribute__((aligned(16))) = {"]
    rev8 = [2 * (15 - k) for k in range(16)]
    rev16 = [2 * ((7 - k // 2) * 2 + k % 2) for k in range(16)]
    assert shufv([None] * 16, list(range(16)), rev8) == list(range(15, -1, -1))
    for row in (il_idx(1, False), il_idx(1, True), il_idx(2, False),
                il_idx(2, True), rev8, rev16):
        out.append("    { %s }," % ", ".join(str(v) for v in row))
    out.append("};\n")
    emit_fn("nv12_mxu2_t16_y", 16, 1, 4, out, False)
    emit_fn("nv12_mxu2_t16_y_rev", 16, 1, 4, out, True)
    emit_fn("nv12_mxu2_t8_uv", 8, 2, 3, out, False)
    emit_fn("nv12_mxu2_t8_uv_rev", 8, 2, 3, out, True)
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
